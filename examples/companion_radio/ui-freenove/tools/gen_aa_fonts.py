#!/usr/bin/env python3
"""Generate ui-freenove/FbFontsAA.{h,cpp}: the anti-aliased proportional
fonts of the HMI theme (FrameBuffer565::text()) and of the companion UI on
the Freenove head (CompanionText.h).

Typeface: D-DIN and D-DIN Bold by Datto Inc., SIL Open Font License 1.1 --
see ../LICENSE.D-DIN-OFL.txt. ("D-DIN" is a Reserved Font Name: the data
here are bitmaps rendered from the unmodified fonts, credited, not a font
distributed under that name.) Source: the Font Squirrel package
  https://www.fontsquirrel.com/fonts/download/d-din
  D-DIN.otf       sha256 6d67834e2a76646c456c087ce42a6bd6b6b0c85c88dd9918618a8b4c563c2bdf
  D-DIN-Bold.otf  sha256 b0f96a3730041605b139ca2d15e29a36c55e49058ba2b72ee4d09b5e4ca210c1

Rendering: each glyph is rasterised by FreeType at its native size with
hinting (Pillow, grayscale anti-aliasing), so stems land on whole pixels;
coverage is stored linearly (gamma 1.0) as 4-bit alpha. Advances are the
hinted advances in 1/4 px; the renderer rounds the running pen position,
never each advance, so spacing does not drift. Pair kerning is taken from
the font's legacy kern table when it has one (D-DIN has none: the table is
empty, the renderer supports it). Each font carries only the glyphs the
pages use; a glyph a font lacks has advance 0 and draws nothing. Code 0xB7
(middle dot, Latin-1) is the one non-ASCII glyph, stored after 0x7E.

Usage:
  python gen_aa_fonts.py <font dir> <out dir (ui-freenove)>

Needs Pillow (>= 10). Deterministic for a given Pillow/FreeType.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7E
DOT = 0xB7

ASCII = ''.join(chr(c) for c in range(FIRST, LAST + 1)) + chr(DOT)
DIGITS = '0123456789'

# name, file, px size (em), glyphs, comment
FONTS = [
    ('kFontSmall', 'D-DIN.otf', 14, ASCII, 'all small UI text (minimum size): labels, notes, units, tabs'),
    ('kFontTile', 'D-DIN-Bold.otf', 15, ASCII, 'quick-control tile labels'),
    ('kFontTitle', 'D-DIN-Bold.otf', 16, ASCII, 'panel titles'),
    ('kFontName', 'D-DIN-Bold.otf', 18, ASCII, 'header: repeater name'),
    ('kFontText20', 'D-DIN.otf', 20, ASCII, 'companion UI text size 2'),
    ('kFontText28', 'D-DIN.otf', 28, ASCII, 'companion UI text size 3+'),
    ('kFontDigits', 'D-DIN-Bold.otf', 22, DIGITS + '-+.%', 'odometer, packet rate and telemetry readings'),
    ('kFontClock', 'D-DIN-Bold.otf', 24, DIGITS + ':T+-', 'header clock / uptime'),
    ('kFontFreq', 'D-DIN-Bold.otf', 26, DIGITS + '.-', 'header frequency'),
    ('kFontBig', 'D-DIN-Bold.otf', 34, DIGITS + '-', 'noise floor reading'),
]

HEADER = '''\
#pragma once

// GENERATED by tools/gen_aa_fonts.py -- do not edit by hand.
//
// Anti-aliased proportional fonts for FrameBuffer565::text(): bitmaps
// rendered (hinted, native size) from D-DIN / D-DIN Bold by Datto Inc.
// (SIL Open Font License 1.1, LICENSE.D-DIN-OFL.txt), 4-bit alpha.
// Codes 0x20..0x7E plus 0xB7 (middle dot) at index 95; glyphs a font does
// not carry have adv 0 and no pixels.

#include <stdint.h>

struct AAGlyph {
  uint32_t offset;  // first byte in the font's bitmap (rows packed, 2 px/byte, high nibble first)
  uint8_t w, h;     // bitmap size
  int8_t x, y;      // bitmap origin from the pen: x right, y from the baseline (negative = up)
  uint8_t adv;      // pen advance in 1/4 px
};

struct AAKern {
  uint8_t a, b;     // glyph indices (aaGlyphIndex)
  int8_t q;         // adjustment in 1/4 px
};

struct AAFont {
  const AAGlyph* glyphs;   // 96 entries
  const uint8_t* bitmap;
  const AAKern* kerns;     // sorted by (a, b); may be null
  uint16_t kernCount;
  uint8_t ascent;          // baseline below the top of the line box (px)
  uint8_t descent;         // below the baseline (px)
  uint8_t size;            // nominal em size (px)
};

constexpr int kAAGlyphs = 96;
// Glyph index for a byte; -1 when the code has no slot.
inline int aaGlyphIndex(unsigned char c) {
  if (c >= 0x20 && c <= 0x7E) return c - 0x20;
  return c == 0xB7 ? 95 : -1;
}
// Kerning between glyph indices a and b (1/4 px), 0 when none.
inline int aaKern(const AAFont& f, int a, int b) {
  int lo = 0, hi = (int)f.kernCount - 1;
  while (lo <= hi) {
    const int mid = (lo + hi) / 2;
    const AAKern& k = f.kerns[mid];
    const int c = k.a != a ? (int)k.a - a : (int)k.b - b;
    if (c == 0) return k.q;
    if (c < 0) lo = mid + 1;
    else hi = mid - 1;
  }
  return 0;
}

'''


def render_font(path, size, glyphs):
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    codes = list(range(FIRST, LAST + 1)) + [DOT]
    entries, bitmap = [], bytearray()
    for code in codes:
        ch = chr(code)
        if ch not in glyphs:
            entries.append((0, 0, 0, 0, 0, 0))
            continue
        adv = int(round(font.getlength(ch) * 4))
        pad = 4
        W = int(font.getlength(ch)) + 2 * pad + size
        H = asc + desc + 2 * pad
        base = pad + asc
        img = Image.new('L', (W, H), 0)
        ImageDraw.Draw(img).text((pad, base), ch, fill=255, font=font, anchor='ls')
        bbox = img.getbbox()
        if bbox is None or ch == ' ':
            entries.append((len(bitmap), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bbox
        px = img.load()
        offset = len(bitmap)
        nib = []
        for y in range(y0, y1):
            for x in range(x0, x1):
                nib.append((px[x, y] * 15 + 127) // 255)
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            bitmap.append((nib[i] << 4) | nib[i + 1])
        entries.append((offset, x1 - x0, y1 - y0, x0 - pad, y0 - base, adv))
    # Legacy kern pairs (empty for D-DIN; kept for other fonts).
    kerns = []
    present = [c for c in codes if chr(c) in glyphs and chr(c) != ' ']
    for a in present:
        la = font.getlength(chr(a))
        for b in present:
            k = font.getlength(chr(a) + chr(b)) - la - font.getlength(chr(b))
            q = int(round(k * 4))
            if q != 0:
                ia = a - FIRST if a != DOT else 95
                ib = b - FIRST if b != DOT else 95
                kerns.append((ia, ib, max(-128, min(127, q))))
    kerns.sort()
    return asc, desc, entries, bitmap, kerns


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    font_dir, out_dir = sys.argv[1], sys.argv[2]
    h = [HEADER]
    cpp = ['// GENERATED by tools/gen_aa_fonts.py -- do not edit by hand.\n'
           '//\n'
           '// Bitmaps rendered from D-DIN / D-DIN Bold: Copyright (C) 2017 Datto Inc.\n'
           '// (https://www.datto.com/fonts/d-din), SIL Open Font License 1.1 --\n'
           '// LICENSE.D-DIN-OFL.txt in this directory.\n\n'
           '#include "FbFontsAA.h"\n']
    total = 0
    for name, file, size, glyphs, what in FONTS:
        asc, desc, entries, bitmap, kerns = render_font(os.path.join(font_dir, file), size, glyphs)
        total += len(bitmap) + len(entries) * 12 + len(kerns) * 3
        h.append('// %s: %s %d px -- %s.\nextern const AAFont %s;\n' % (name, file, size, what, name))
        cpp.append('\nstatic const uint8_t %sBits[%d] = {' % (name, max(1, len(bitmap))))
        data = list(bitmap) or [0]
        for i in range(0, len(data), 16):
            cpp.append('\n  ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
        cpp.append('\n};\n')
        cpp.append('static const AAGlyph %sGlyphs[kAAGlyphs] = {' % name)
        for i, (off, w, hh, x, y, adv) in enumerate(entries):
            code = FIRST + i if i < 95 else DOT
            label = chr(code) if 0x21 <= code <= 0x7E and chr(code) != '\\' else '0x%02X' % code
            cpp.append('\n  {%d, %d, %d, %d, %d, %d},  // %s' % (off, w, hh, x, y, adv, label))
        cpp.append('\n};\n')
        if kerns:
            cpp.append('static const AAKern %sKerns[%d] = {' % (name, len(kerns)))
            for a, b, q in kerns:
                cpp.append('\n  {%d, %d, %d},' % (a, b, q))
            cpp.append('\n};\n')
            kref = '%sKerns, %d' % (name, len(kerns))
        else:
            kref = 'nullptr, 0'
        cpp.append('const AAFont %s = {%sGlyphs, %sBits, %s, %d, %d, %d};\n'
                   % (name, name, name, kref, asc, desc, size))
    h.append('\n// The HMI pages use one minimum size for all body text.\n'
             'static const AAFont& kFontBody = kFontSmall;\n')
    open(os.path.join(out_dir, 'FbFontsAA.h'), 'w', newline='\n').write(''.join(h))
    open(os.path.join(out_dir, 'FbFontsAA.cpp'), 'w', newline='\n').write(''.join(cpp))
    print('fonts: %d bytes of glyph data' % total)
    return 0


if __name__ == '__main__':
    sys.exit(main())
