def font6x8(glcd_path):
    text = open(glcd_path, encoding='latin-1').read()
    body = text[text.index('font[]'):]
    body = body[body.index('{') + 1:body.index('};')]
    data = [int(v, 16) for v in re.findall(r'0x[0-9A-Fa-f]{2}', body)]
    out = []
    for c in range(FIRST, LAST + 1):
        cols = data[c * 5:c * 5 + 5]
        for row in range(8):
            bits = 0
            for x, col in enumerate(cols):
                if col & (1 << row):
                    bits |= 0x80 >> x
            out.append(bits)
    return out


def font8x16(ttf_path):
    font = ImageFont.truetype(ttf_path, 14)
    out = []
    for c in range(FIRST, LAST + 1):
        # Render on a wide canvas, then place the ink inside the 8-px cell.
        im = Image.new('L', (24, 24), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = '1'
        d.text((8, 16), chr(c), fill=255, font=font, anchor='ls')
        shift = 0
        box = im.getbbox()
        if box is not None:
            if box[2] > 16:              # spills right: move left if room
                shift = min(box[2] - 16, box[0] - 8)
            if box[2] - box[0] > 8 or box[1] < 4 or box[3] > 20:
                raise SystemExit('glyph %r does not fit 8x16: %r' % (chr(c), box))
        for row in range(16):
            bits = 0
            for x in range(8):
                if im.getpixel((8 + x + shift, 4 + row)) >= 128:
                    bits |= 0x80 >> x
            out.append(bits)
    return out


def emit(name, data, per_glyph):
    lines = ['const uint8_t %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), per_glyph):
        c = FIRST + i // per_glyph
        hexes = ', '.join('0x%02X' % b for b in data[i:i + per_glyph])
        label = "'\\\\'" if chr(c) == '\\' else repr(chr(c))
        lines.append('  %s,  // %s' % (hexes, label))
    lines.append('};')
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    glcd, ttf, out = sys.argv[1:]
    src = [
        '// GENERATED by tools/gen_fonts.py -- do not edit by hand.',
        '//',
        '// Monospace bitmap fonts for FrameBuffer332::text(), printable ASCII',
        '// 0x20..0x7E, row-major, bit 7 = leftmost pixel.',
        '//',
        BSD.rstrip('\n'),
        '',
        '#include "FbFonts.h"',
        '',
        emit('kFont6x8', font6x8(glcd), 8),
        '',
        emit('kFont8x16', font8x16(ttf), 16),
        '',
    ]
    with open(out, 'w', newline='\n', encoding='ascii') as f:
        f.write('\n'.join(src))


if __name__ == '__main__':
    main()
